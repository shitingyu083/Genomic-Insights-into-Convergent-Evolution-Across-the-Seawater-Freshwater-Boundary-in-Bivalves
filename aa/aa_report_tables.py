# Build aa_report_tables.md (Tables A-F of aa_report.md) directly from the result TSVs; run from analysis/aa.
import csv

def load(p):
    with open(p, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))

pg, gt, pc, tr = (load(p) for p in ("aa_pgls_results.tsv", "aa_gc_tests.tsv", "aa_gc_proxy_cor.tsv", "aa_gc_trcheck.tsv"))
DS = ["ALL_ANY", "OGREP_ANY", "SC8_OGC", "SC36_OGC", "ALL_EXT", "ALL_MEM", "ALL_CYT", "OGREP_EXT"]
MS = {"1": "m1 main", "2": "m2 euhaline-only", "3": "m3 BUSCO-excl.", "4": "m4 adjusted",
      "5": "m5 adj. + euhaline-only", "6": "m6 adj. + BUSCO-excl."}
AA = "ACDEFGHIKLMNPQRSTVWY"
f4 = lambda x: f"{float(x):.4f}"
g3 = lambda x: f"{float(x):.3g}"

def R(d, a, m):
    r = [x for x in pg if x["dataset"] == d and x["aa"] == a and x["model"].split()[0] == m]
    assert len(r) == 1, (d, a, m)
    return r[0]

L = ["# Tables for aa_report.md (generated by aa_report_tables.py from the result TSVs; do not edit by hand)", ""]
L += ["## Table A. Sample sizes (species; FW in brackets) per protein set and model", "",
      "| set | " + " | ".join(MS.values()) + " |", "|---" * 7 + "|"]
for d in DS:
    L.append(f"| {d} | " + " | ".join(f"{R(d, 'G', m)['n']} ({R(d, 'G', m)['n_FW']})" for m in MS) + " |")
for a, nm in zip("GAPQ", ["Gly", "Ala", "Pro", "Gln"]):
    L += ["", f"## Table B-{a}. {nm}: beta_FW (CLR units) [95% CI]; P; q (BH over 20 residues within set x model)", "",
          "| set | " + " | ".join(MS.values()) + " |", "|---" * 7 + "|"]
    for d in DS:
        c = []
        for m in MS:
            r = R(d, a, m)
            c.append(f"{f4(r['beta_FW'])} [{f4(r['ci_lo'])}, {f4(r['ci_hi'])}]; {g3(r['P'])}; {g3(r['q_BH'])}")
        L.append(f"| {d} | " + " | ".join(c) + " |")
L += ["", "## Table C. Main model (m1), all protein models (ALL_ANY), all 20 residues", "",
      "| aa | mean CLR FW | mean CLR comparators | raw difference | lambda | beta_FW [95% CI] | P | q |", "|---" * 8 + "|"]
for a in AA:
    r = R("ALL_ANY", a, "1")
    L.append(f"| {a} | {f4(r['mean_FW'])} | {f4(r['mean_comp'])} | {f4(r['diff_means'])} | {float(r['lambda']):.3f} | "
             f"{f4(r['beta_FW'])} [{f4(r['ci_lo'])}, {f4(r['ci_hi'])}] | {g3(r['P'])} | {g3(r['q_BH'])} |")
L += ["", "## Table D. All set x model x residue cells with q < 0.05 (of 960 fits)", "",
      "| aa | cells (of 48) | beta range | cells |", "|---|---|---|---|"]
for a in AA:
    s = [x for x in pg if x["aa"] == a and float(x["q_BH"]) < 0.05]
    if not s:
        L.append(f"| {a} | 0 | - | - |")
        continue
    b = [float(x["beta_FW"]) for x in s]
    cells = "; ".join(f"{x['dataset']} m{x['model'].split()[0]} {f4(x['beta_FW'])} (q {g3(x['q_BH'])})" for x in s)
    L.append(f"| {a} | {len(s)} | {min(b):.4f} to {max(b):.4f} | {cells} |")
L.append(f"\nTotal cells with q < 0.05: {sum(float(x['q_BH']) < 0.05 for x in pg)} of {len(pg)}.")
L += ["", "## Table E. CDS check: translated CDS vs proteome composition (12 species with a CDS file on the server)", "",
      "| species | class | CDS headers match proteome | CDS used / proteins | TVD | max abs. difference |", "|---" * 6 + "|"]
for r in tr:
    L.append(f"| {r['species']} | {r['salinity3']} | {r['header_count_matches']} | {r['n_cds_used']} / {r['n_prot']} | "
             f"{float(r['TVD']):.2g} | {float(r['max_abs_diff']):.2g} |")
L += ["", "## Table F. CDS GC and GC-adjusted composition (S10 = 10 matched species: Cfl, Dpo, Dro, Lfo, Pst vs Cgi, Csi,"
      " Tna, Sco, Sbr; S9 = S10 without Lfo; S12 = all 12)", "",
      "| set | response | model | n (FW) | mean FW | mean comparators | Wilcoxon P | lambda | beta_FW [95% CI] | P | covariate |",
      "|---" * 11 + "|"]
for r in gt:
    mf = f"{float(r['mean_FW']):.4f}" if r["mean_FW"] else ""
    mc = f"{float(r['mean_comp']):.4f}" if r["mean_comp"] else ""
    wp = g3(r["wilcox_P"]) if r["wilcox_P"] not in ("", "NA") else ""
    L.append(f"| {r['set']} | {r['response']} | {r['model']} | {r['n']} ({r['n_FW']}) | {mf} | {mc} | {wp} | "
             f"{float(r['lambda']):.3f} | {f4(r['beta_FW'])} [{f4(r['ci_lo'])}, {f4(r['ci_hi'])}] | {g3(r['P'])} | {r['other']} |")
L += ["", "## Table G. Spearman correlations of CDS GC3/GC4 with the proteome GC proxy and CLR", "",
      "| set | x | y | n | rho | P |", "|---" * 6 + "|"]
for r in pc:
    p = float(r["P"])
    L.append(f"| {r['set']} | {r['x']} | {r['y']} | {r['n']} | {float(r['rho']):.3f} | {'< 0.001' if p < 0.001 else g3(p)} |")
open("aa_report_tables.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
print(len(L), "lines")
